#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct PairingSession {
    pub session_token: String,
    pub created_at: i64,
    pub expires_at: i64,
}

impl AppState {
    /// True if `presented` is a valid console credential: this run's host session token
    /// (the bootstrap / local-console secret), or a persistent console credential that
    /// was issued to a browser earlier and hasn't been revoked in Paired Devices.
    pub fn is_console_credential(&self, presented: &str) -> bool {
        let presented = presented.trim();
        if presented.is_empty() {
            return false;
        }
        if !self.host_session_token.is_empty() && crate::api::ct_eq(presented, &self.host_session_token) {
            return true;
        }
        // Console credentials are high-entropy random strings; only those can match a
        // stored hash, so a cheap prefix check keeps device-token probes off this path.
        if !presented.starts_with("console_tok_") {
            return false;
        }
        let hashed = crate::storage::db::console_credential_hash(presented);
        match self.db.get_paired_device_by_token(&hashed) {
            Ok(Some(dev)) if dev.platform == crate::storage::db::CONSOLE_PLATFORM => {
                // Throttled "last seen" so the Paired Devices list shows real activity
                // without a database write on every request.
                let now = chrono::Utc::now().timestamp_millis();
                if now - dev.last_seen > 60_000 {
                    let _ = self.db.touch_paired_device(&dev.id);
                }
                true
            }
            _ => false,
        }
    }

    /// Issues a capability token for a plugin with the default scope (its own keyring).
    pub async fn issue_plugin_token(&self, plugin_name: &str) -> String {
        self.issue_plugin_token_scoped(plugin_name, PermissionSet(vec![PermissionRequest::simple("keyring.own")])).await
    }

    /// Issues a token carrying `scopes`. Tokens expire after `PLUGIN_TOKEN_TTL_SECS`, and a
    /// plugin holds at most `PLUGIN_TOKENS_PER_PLUGIN` at once (the oldest is dropped), so the
    /// map can't grow without bound.
    pub async fn issue_plugin_token_scoped(&self, plugin_name: &str, scopes: PermissionSet) -> String {
        let token = format!("plg_{}", uuid::Uuid::new_v4().simple());
        let now = chrono::Utc::now().timestamp();
        let plugin = plugin_name.trim().to_string();
        let mut tokens = self.plugin_tokens.write().await;
        tokens.retain(|_, t| t.expires_at > now);
        let mut mine: Vec<(String, i64)> =
            tokens.iter().filter(|(_, t)| t.plugin_id == plugin).map(|(k, t)| (k.clone(), t.expires_at)).collect();
        if mine.len() >= PLUGIN_TOKENS_PER_PLUGIN {
            mine.sort_by_key(|(_, exp)| *exp);
            for (t, _) in mine.iter().take(mine.len() + 1 - PLUGIN_TOKENS_PER_PLUGIN) {
                tokens.remove(t);
            }
        }
        tokens.insert(token.clone(), PluginTokenInfo { plugin_id: plugin, scopes, expires_at: now + PLUGIN_TOKEN_TTL_SECS });
        token
    }

    /// Resolves a plugin capability token to its associated plugin name, if it hasn't expired.
    pub async fn resolve_plugin_token(&self, token: &str) -> Option<String> {
        let now = chrono::Utc::now().timestamp();
        let tokens = self.plugin_tokens.read().await;
        tokens.get(token.trim()).filter(|t| t.expires_at > now).map(|t| t.plugin_id.clone())
    }

    /// Resolves a token to the plugin and what it may do *right now*: the token's scopes
    /// narrowed by the plugin's current grant, and nothing at all unless the plugin is still
    /// approved and unchanged.
    pub async fn resolve_plugin_caller(&self, token: &str) -> Option<PluginCaller> {
        let now = chrono::Utc::now().timestamp();
        let (plugin_id, scopes) = {
            let tokens = self.plugin_tokens.read().await;
            let t = tokens.get(token.trim()).filter(|t| t.expires_at > now)?;
            (t.plugin_id.clone(), t.scopes.clone())
        };
        let row = self.db.get_plugin_grant(&plugin_id).ok().flatten()?;
        if row.effective_state() != "active" {
            return None;
        }
        let granted = crate::core::plugin_registry::parse_granted(&row);
        Some(PluginCaller { plugin_id, scopes: scopes.narrowed_by(&granted) })
    }

    /// Drops every token a plugin holds (called when it is denied or revoked).
    pub async fn revoke_plugin_tokens(&self, plugin_name: &str) {
        self.plugin_tokens.write().await.retain(|_, t| t.plugin_id != plugin_name);
    }

    /// Creates an ephemeral pairing session with TTL (in seconds, default 300)
    pub async fn create_pairing_session(&self, ttl_seconds: u64) -> String {
        let session_token = format!("pair_sess_{}", uuid::Uuid::new_v4().simple());
        let now = chrono::Utc::now().timestamp();
        let expires_at = now + ttl_seconds as i64;
        let session = PairingSession {
            session_token: session_token.clone(),
            created_at: now,
            expires_at,
        };
        let mut sessions = self.pairing_sessions.write().await;
        // Prune expired sessions
        sessions.retain(|_, s| s.expires_at >= now);
        sessions.insert(session_token.clone(), session);
        session_token
    }

    /// Validates an ephemeral pairing session token against its TTL. Does NOT
    /// consume it — a technician pairing several TVs from one console-minted
    /// session (the "Pair Another Display" flow in `pairing.html`) authorizes
    /// each device against the same still-live session, rather than the
    /// phone minting a fresh session itself (which would require the phone
    /// to hold console-level trust it was never meant to have). It naturally
    /// stops working once `expires_at` passes, same as before.
    pub async fn validate_pairing_session(&self, token: &str) -> bool {
        let now = chrono::Utc::now().timestamp();
        let sessions = self.pairing_sessions.read().await;
        sessions
            .get(token.trim())
            .map(|session| session.expires_at >= now)
            .unwrap_or(false)
    }

    /// "One console at a time, first one connected wins." `Ok(())` if
    /// `session_id` may proceed -- either it already owns the lock, or the
    /// lock was free and this call just claimed it for it. `Err(())` means a
    /// *different* console session already holds it; callers should reject
    /// the request/message with a distinct reason rather than the generic
    /// auth-failure one, so the UI can say "another console is connected"
    /// instead of implying the token itself was wrong.
    pub fn try_claim_console(&self, session_id: &str) -> Result<(), ()> {
        let mut guard = self.active_console.lock().unwrap_or_else(|e| e.into_inner());
        let fresh = || ConsoleLock { session_id: session_id.to_string(), ws_conns: 0, last_seen: std::time::Instant::now() };
        match guard.as_mut() {
            Some(cur) if cur.session_id == session_id => {
                cur.last_seen = std::time::Instant::now();
                Ok(())
            }
            // Abandoned HTTP-only claim: nothing will ever release it.
            Some(cur) if cur.ws_conns == 0 && cur.last_seen.elapsed() > CONSOLE_HTTP_IDLE => {
                *guard = Some(fresh());
                Ok(())
            }
            Some(_) => Err(()),
            None => {
                *guard = Some(fresh());
                Ok(())
            }
        }
    }

    /// Records that a WebSocket connection is now backing `session_id`'s lock.
    pub fn attach_console_ws(&self, session_id: &str) {
        let mut guard = self.active_console.lock().unwrap_or_else(|e| e.into_inner());
        if let Some(cur) = guard.as_mut() {
            if cur.session_id == session_id {
                cur.ws_conns += 1;
            }
        }
    }

    /// Called when one of `session_id`'s sockets disconnects. Frees the lock
    /// once it has no live sockets left; a no-op if another session holds it.
    pub fn release_console_if_held(&self, session_id: &str) {
        let mut guard = self.active_console.lock().unwrap_or_else(|e| e.into_inner());
        if let Some(cur) = guard.as_mut() {
            if cur.session_id == session_id {
                cur.ws_conns = cur.ws_conns.saturating_sub(1);
                if cur.ws_conns == 0 {
                    *guard = None;
                }
            }
        }
    }
}

/// Shared side effects for every command entry point (HTTP `POST /api/command` and native
/// WS command messages): notify plugins, then broadcast the new state to all connected
/// clients — omitting `schedule` from the broadcast when it hasn't changed since the last
/// one, since every already-connected client already has the current schedule. Returns the
/// full, untouched snapshot so callers needing complete fidelity (an HTTP response body)
/// don't have to re-snapshot.
pub fn broadcast_snapshot(app: &AppState) -> StateSnapshot {
    let snapshot = app.engine.snapshot();
    app.plugin_manager.notify_state_change(&snapshot.state);

    let current_version = snapshot.schedule.schedule_version;
    let previous_version = app
        .last_broadcast_schedule_version
        .swap(current_version, Ordering::Relaxed);
    let schedule_changed = previous_version != current_version;

    if let Ok(mut value) = serde_json::to_value(&snapshot) {
        if !schedule_changed {
            value["schedule"] = serde_json::Value::Null;
        }
        if let Ok(json_str) = serde_json::to_string(&value) {
            let _ = app.tx.send(json_str);
        }
    }

    snapshot
}

pub async fn ws_handler(
    ws: WebSocketUpgrade,
    State(app_state): State<AppState>,
    connect_info: Option<ConnectInfo<std::net::SocketAddr>>,
    headers: HeaderMap,
) -> impl IntoResponse {
    // In "restricted" CORS mode a browser page from a foreign origin must not
    // be able to open a socket either (CORS doesn't cover WebSocket upgrades).
    // Non-browser clients send no Origin and are unaffected.
    if let Some(origin) = headers.get(axum::http::header::ORIGIN).and_then(|v| v.to_str().ok()) {
        let restricted = app_state
            .security_header_settings
            .read()
            .unwrap_or_else(|e| e.into_inner())
            .cors_mode
            == "restricted";
        if restricted && !crate::api::routes::is_allowed_sanctuary_origin(origin) {
            return (axum::http::StatusCode::FORBIDDEN, "origin not allowed").into_response();
        }
    }
    // Cap frame/message size (axum defaults are 16/64 MiB) and concurrent
    // sockets, globally and per peer: /ws is readable cross-origin by design,
    // so one unauthenticated peer must not be able to pin memory, the DB
    // mutex, or every slot the real consoles/displays need.
    let ip_guard = match connect_info.map(|ConnectInfo(a)| IpSlot::acquire(a.ip())) {
        Some(Some(g)) => Some(g),
        // No peer address available (not served with connect info): global cap only.
        None => None,
        Some(None) => return (axum::http::StatusCode::TOO_MANY_REQUESTS, "too many connections from this address").into_response(),
    };
    let permit = match WS_CONNECTIONS.clone().try_acquire_owned() {
        Ok(p) => p,
        Err(_) => return (axum::http::StatusCode::SERVICE_UNAVAILABLE, "too many connections").into_response(),
    };
    ws.max_message_size(WS_MAX_MESSAGE_BYTES)
        .max_frame_size(WS_MAX_MESSAGE_BYTES)
        .on_upgrade(move |socket| async move {
            let _permit = permit;
            let _ip_guard = ip_guard;
            handle_socket(socket, app_state).await
        })
        .into_response()
}

/// Per-peer concurrent socket cap. Loopback gets a larger allowance because a
/// local reverse proxy makes many real visitors share one address.
const WS_MAX_PER_IP: usize = 16;
const WS_MAX_PER_LOOPBACK: usize = 128;
/// Server pings every `WS_PING_INTERVAL`; a socket that sends nothing (not even
/// the automatic pong) for `WS_IDLE_TIMEOUT` is dropped, freeing its slot.
const WS_PING_INTERVAL: std::time::Duration = std::time::Duration::from_secs(30);
const WS_IDLE_TIMEOUT: std::time::Duration = std::time::Duration::from_secs(120);

static WS_PER_IP: std::sync::LazyLock<std::sync::Mutex<std::collections::HashMap<std::net::IpAddr, usize>>> =
    std::sync::LazyLock::new(|| std::sync::Mutex::new(std::collections::HashMap::new()));

struct IpSlot(std::net::IpAddr);

impl IpSlot {
    fn acquire(ip: std::net::IpAddr) -> Option<IpSlot> {
        let limit = if ip.is_loopback() { WS_MAX_PER_LOOPBACK } else { WS_MAX_PER_IP };
        let mut map = WS_PER_IP.lock().unwrap_or_else(|e| e.into_inner());
        let n = map.entry(ip).or_insert(0);
        if *n >= limit {
            return None;
        }
        *n += 1;
        Some(IpSlot(ip))
    }
}

impl Drop for IpSlot {
    fn drop(&mut self) {
        let mut map = WS_PER_IP.lock().unwrap_or_else(|e| e.into_inner());
        if let Some(n) = map.get_mut(&self.0) {
            *n = n.saturating_sub(1);
            if *n == 0 {
                map.remove(&self.0);
            }
        }
    }
}

const WS_MAX_MESSAGE_BYTES: usize = 8 * 1024 * 1024;
const WS_MAX_CONNECTIONS: usize = 256;

static WS_CONNECTIONS: std::sync::LazyLock<std::sync::Arc<tokio::sync::Semaphore>> =
    std::sync::LazyLock::new(|| std::sync::Arc::new(tokio::sync::Semaphore::new(WS_MAX_CONNECTIONS)));

/// The frame as logged / shown to plugins: credentials stripped.
fn redact_ws_envelope(value: &serde_json::Value) -> String {
    let mut v = value.clone();
    if let Some(obj) = v.as_object_mut() {
        for k in ["host_token", "device_token", "plugin_token", "console_session_id"] {
            obj.remove(k);
        }
    }
    v.to_string()
}

async fn handle_socket(socket: WebSocket, app_state: AppState) {
    let (mut sender, mut receiver) = socket.split();

    // 1. Send initial StateSnapshot directly (as raw JSON)
    let snapshot = app_state.engine.snapshot();
    if let Ok(json_str) = serde_json::to_string(&snapshot) {
        let _ = sender.send(Message::Text(json_str)).await;
    }

    // 2. Spawn task to broadcast updates to this client. Also carries direct,
    // this-connection-only replies (e.g. a "console_locked" rejection) that
    // don't belong on the shared broadcast -- see the `direct_tx` send below.
    let mut rx = app_state.tx.subscribe();
    let (direct_tx, mut direct_rx) = tokio::sync::mpsc::unbounded_channel::<String>();
    let mut send_task = tokio::spawn(async move {
        let mut ping = tokio::time::interval(WS_PING_INTERVAL);
        ping.tick().await;
        loop {
            tokio::select! {
                _ = ping.tick() => {
                    if sender.send(Message::Ping(Vec::new())).await.is_err() {
                        break;
                    }
                }
                msg = rx.recv() => {
                    match msg {
                        Ok(msg) => {
                            if sender.send(Message::Text(msg)).await.is_err() {
                                break;
                            }
                        }
                        Err(tokio::sync::broadcast::error::RecvError::Lagged(_)) => continue,
                        Err(tokio::sync::broadcast::error::RecvError::Closed) => break,
                    }
                }
                Some(direct) = direct_rx.recv() => {
                    if sender.send(Message::Text(direct)).await.is_err() {
                        break;
                    }
                }
            }
        }
    });

    let app = app_state.clone();

    // 3. Process incoming messages from client
    let mut recv_task = tokio::spawn(async move {
        // Releases the "one console at a time" lock (if this connection
        // ever claimed it) when this task's future is dropped -- which
        // happens both on a clean loop exit below AND when `recv_task.abort()`
        // cancels it from the `tokio::select!` at the bottom of
        // `handle_socket` (an abrupt client disconnect, not just the loop
        // ending on its own). A plain "release after the loop" statement
        // would silently never run in the abort case, permanently wedging
        // the lock until the server restarts.
        struct ConsoleLockGuard {
            app: AppState,
            session_id: Option<String>,
        }
        impl Drop for ConsoleLockGuard {
            fn drop(&mut self) {
                if let Some(id) = self.session_id.take() {
                    self.app.release_console_if_held(&id);
                }
            }
        }
        let mut console_lock = ConsoleLockGuard { app: app.clone(), session_id: None };

        while let Ok(Some(Ok(msg))) = tokio::time::timeout(WS_IDLE_TIMEOUT, receiver.next()).await {
            if let Message::Text(text) = msg {
                // Intercept raw JSON commands
                if let Ok(value) = serde_json::from_str::<serde_json::Value>(&text) {
                    let safe_text = redact_ws_envelope(&value);
                    // Every command arrives in an envelope that carries its own credential, since
                    // a raw WebSocket text frame has no header to put one in:
                    //   {"cmd": <ShowCommand>, "plugin_token": "..."}    an approved plugin
                    //   {"cmd": <ShowCommand>, "device_token": "..."}    a paired remote (/remote)
                    //   {"cmd": <ShowCommand>, "host_token": "...", "console_session_id": "..."}
                    //                                                    the operator console
                    // (docs/CLIENT_PAIRING.md "Console (host) authentication"). Only the real
                    // console ever obtains the host token (native injection, a loopback-only
                    // fetch, or a persistent console credential), which is what closes the
                    // "any LAN caller could drive the show" gap. The same checks and the same
                    // execution path as REST: see `command_pipeline`.
                    let str_field = |name: &str| value.get(name).and_then(|v| v.as_str()).map(|s| s.to_string());
                    let plugin_token = str_field("plugin_token");
                    let device_token = str_field("device_token");
                    let host_token = str_field("host_token").unwrap_or_default();
                    let session_id = str_field("console_session_id").unwrap_or_default();
                    let credential = if let Some(t) = plugin_token.as_deref() {
                        CommandCredential::Plugin { token: t }
                    } else if let Some(t) = device_token.as_deref() {
                        CommandCredential::Device { token: t }
                    } else {
                        CommandCredential::Host { token: &host_token, session_id: &session_id }
                    };
                    let cmd_value = value.get("cmd").cloned().unwrap_or(serde_json::Value::Null);

                    let origin = match authenticate_command(&app, &credential, &cmd_value).await {
                        Ok(o) => o,
                        Err(e) => {
                            tracing::warn!("WebSocket command rejected: {}", e.log_line());
                            if e == CommandAuthError::ConsoleLocked {
                                // A distinct, visible rejection rather than a silent drop, so the
                                // second console can say "another console is connected".
                                let _ = direct_tx.send(serde_json::json!({
                                    "error": "console_locked",
                                    "message": "Another console is already connected. Only one console can control the show at a time.",
                                }).to_string());
                            }
                            continue;
                        }
                    };
                    // `console_session_id` is a random id the frontend generates once per page
                    // load, so this connection's own reconnects/HTTP fallback keep working. Tie
                    // the lock to this socket so it is released when the socket goes.
                    if let CommandOrigin::Console { session_id } = &origin {
                        if console_lock.session_id.as_deref() != Some(session_id.as_str()) {
                            if let Some(old) = console_lock.session_id.take() {
                                app.release_console_if_held(&old);
                            }
                            app.attach_console_ws(session_id);
                            console_lock.session_id = Some(session_id.clone());
                        }
                    }

                    if let Err(e) = run_command_pipeline(&app, cmd_value, &origin) {
                        tracing::debug!("WebSocket command dropped: {:?} (raw: {})", e, safe_text);
                    }
                }
            }
        }
    });

    tokio::select! {
        _ = (&mut send_task) => recv_task.abort(),
        _ = (&mut recv_task) => send_task.abort(),
    };
}
